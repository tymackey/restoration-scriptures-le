export function formatLegacyChapterRange(values: readonly number[]): string {
    const chapters = [...new Set(values)]
        .filter((chapter) => Number.isInteger(chapter) && chapter > 0)
        .sort((a, b) => a - b);
    if (!chapters.length) return "";

    const ranges: string[] = [];
    let start = chapters[0];
    let end = start;
    const appendRange = () => {
        ranges.push(start === end ? `${start}` : `${start}-${end}`);
    };
    for (const chapter of chapters.slice(1)) {
        if (chapter === end + 1) {
            end = chapter;
        } else {
            appendRange();
            start = end = chapter;
        }
    }
    appendRange();
    return ranges.join(", ");
}

type ChapterLabelItem = {
    name: string;
    volume_id: string;
    book_id: string;
    book_chapter: number | string;
};

export function formatChapterListLabel(item: ChapterLabelItem): string {
    let suffix = "";
    const key = `${item.book_id}:${item.book_chapter}`;
    if (["bofm", "cc"].includes(item.volume_id)) {
        const range = formatLegacyChapterRange(legacyChapterRanges[key] ?? []);
        if (range) suffix = `LE ${range}`;
    } else if (["oc", "nt"].includes(item.volume_id)) {
        const bibleKey = `${item.volume_id}:${key}`;
        const range = formatLegacyChapterRange(bibleChapterRanges[bibleKey] ?? []);
        suffix = range ? `LE ${range}` : (alternateChapterLabels[bibleKey] ?? "");
    } else if (item.volume_id === "tc") {
        const references = dcVerseReferences[key];
        if (references) {
            suffix = "D&C " + Object.entries(references)
                .sort(([a], [b]) => Number(a) - Number(b))
                .map(([section, verses]) => `${section}:${formatLegacyChapterRange(verses)}`)
                .join("; ");
        } else if (key === "section:1") {
            // Section 1 opens the nested Joseph Smith History chapter picker.
            const sections = Object.entries(dcVerseReferences)
                .filter(([reference]) => reference.startsWith("jshistory:"))
                .flatMap(([, references]) => Object.keys(references).map(Number));
            const range = formatLegacyChapterRange(sections);
            if (range) suffix = `D&C ${range} selections`;
        }
    }
    return suffix ? `${item.name} (${suffix})` : item.name;
}

// Single-chapter books open the reader directly, bypassing the chapter picker.
export function formatBookListLabel(item: {
    name: string;
    volume_id: string;
    id: string;
    num_chapters: number;
}): string {
    if (item.num_chapters !== 1 || !["oc", "nt"].includes(item.volume_id)) return item.name;
    return formatChapterListLabel({ ...item, book_id: item.id, book_chapter: 1 });
}
